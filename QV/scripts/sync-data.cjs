const fs = require('node:fs');
const path = require('node:path');
const core = require('../core.js');
const root = path.resolve(__dirname, '..');
const source = path.resolve(process.argv[2] || path.join(root, '..', 'query.md'));
const markdown = fs.readFileSync(source, 'utf8');
const result = core.parseMarkdown(markdown);
const cards = core.validateCards(result.cards);
if (!cards.length) throw new Error('源文件未发现完整问答，不覆盖现有题库。');
const data = { version: 1, source: path.basename(source), generatedAt: new Date().toISOString(), cards };
fs.mkdirSync(path.join(root, 'data'), { recursive: true });
fs.writeFileSync(path.join(root, 'data', 'cards.js'), '/* Generated by scripts/sync-data.cjs */\nwindow.QV_SEED = ' + JSON.stringify(data, null, 2).replace(/</g, '\\u003c') + ';\n');
fs.writeFileSync(path.join(root, 'data', 'query.md'), markdown);
console.log(`已生成 ${cards.length} 条问答；源文件：${source}`);
result.warnings.forEach(w => console.warn(w));
